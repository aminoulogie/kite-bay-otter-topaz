/**
 * A core vocabulary to draw a word a day from.
 *
 * Deliberately not enormous. A list of ten thousand words scraped from a corpus
 * would look more impressive in a commit and be worse to learn from: the top of
 * a frequency list is where the leverage is, and a list nobody has checked is a
 * list that teaches you mistakes. Everything here is common, unambiguous
 * vocabulary — the kind that appears in the first months of any course — and
 * the point is that you can trust a word you drew without looking it up again.
 *
 * Add your own in the app; the shipped list is a starting point, not a limit.
 *
 * Chinese carries pinyin, because a character without its reading is not yet a
 * word you can say.
 */

export type LangCode = "zh" | "de" | "it" | "es";

export interface LangMeta {
  code: LangCode;
  name: string;
  /** The flag is a shorthand for the language, not a claim about a country. */
  flag: string;
  /** True where a reading is needed as well as the written form. */
  romanised: boolean;
}

